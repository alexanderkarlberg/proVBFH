c Glue between proVBFH-cs and the VBFNLO matrix elements of proVBFH
c (option A, docs/DESIGN.md), called without the POWHEG-BOX machinery.
c Momenta p(0:3,6) in the ordering of proVBFH's H+3j Born:
c   1, 2 incoming partons of line 1 and line 2, 3 Higgs,
c   4, 5 outgoing quarks of line 1 and line 2, 6 the extra parton.
c Flavours bflav(6) as in proVBFH's flavour lists (PDG, gluon = 0, the
c Higgs entry is not used).
c---------------------------------------------------------------------
      subroutine cs_init_vbfnlo
      implicit none
      include 'nlegborn.h'
      include 'pwhg_flst.h'
      include 'pwhg_st.h'
      integer j
c     couplings, masses and widths from vbfnlo.input/powheg.input, as in
c     proVBFH
      call init_couplings
c     alpha_s is applied by proVBFH-cs per line (scales per line)
      st_alpha = 1d0
      st_muren2 = 1d4
c     no tags: compborn_hjjj returns both lines, split in born_col(1:2)
      flst_cur_iborn = 1
      do j=1,nlegborn
         flst_borntags(j,1) = 0
      enddo
      end
c---------------------------------------------------------------------
c |M|^2 (averaged over initial spins and colours, alpha_s = 1) of
c q q -> q q g H and crossings, for the extra parton emitted from
c line 1, (p1, p4), and from line 2, (p2, p5).
      subroutine cs_hjjj_lines(p,bflav,m1,m2)
      implicit none
      include 'nlegborn.h'
      double precision p(0:3,nlegborn),m1,m2
      integer bflav(nlegborn)
      double precision born,bmunu(0:3,0:3,nlegborn),
     $     bornjk(nlegborn,nlegborn),borncol(2)
      call calc_als
      call ctrans(1)
      call compborn_hjjj(p,bflav,born,bmunu,bornjk,borncol)
      m1 = borncol(1)
      m2 = borncol(2)
      end
c---------------------------------------------------------------------
c stand-ins for POWHEG-BOX routines referenced by the files above but
c not used by proVBFH-cs
      double precision function pwhg_alphas(q2,xlam,inf)
c     used by convert_coup.f (KOPPLN: running quark masses for the Higgs
c     partial widths, and the HELAS strong coupling, which the VBFNLO
c     Born, real and virtual routines do not use: they take alpha_s from
c     scales.inc, i.e. st_alpha). HOPPET's running coupling, which
c     inclusive_init sets up before cs_init_vbfnlo is called.
      implicit none
      double precision q2,xlam,hoppetAlphaS
      integer inf
      external hoppetAlphaS
      pwhg_alphas = hoppetAlphaS(sqrt(q2))
      end

