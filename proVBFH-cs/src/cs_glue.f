c---------------------------------------------------------------------
c the VBF Born point generated by the inclusive phase space (gen_phsp):
c momenta (1, 2 incoming, 3 Higgs, 4, 5 outgoing quarks of lines 1, 2),
c momentum fractions, phase-space Jacobian and beam energy squared
      subroutine cs_get_born(p,xb1,xb2,jac,sbeams)
      implicit none
c     the /pwhg_kn/ layout of the inclusive phase space (phase_space.f
c     declares nlegborn = 5; the VBFNLO/POWHEG files use 6 but do not
c     touch /pwhg_kn/)
      integer nlegborn, nlegreal
      parameter (nlegborn = 5)
      parameter (nlegreal = nlegborn + 1)
      include 'pwhg_kn.h'
      double precision p(0:3,5),xb1,xb2,jac,sbeams
      integer j,mu
      do j=1,5
         do mu=0,3
            p(mu,j) = kn_pborn(mu,j)
         enddo
      enddo
      xb1 = kn_xb1
      xb2 = kn_xb2
      jac = kn_jacborn
      sbeams = kn_sbeams
      end
c---------------------------------------------------------------------
c momenta (E,px,py,pz) of n particles (1, 2 incoming, 3 Higgs, the
c rest outgoing partons) into the HEPEVT arrays read by user_analysis
      subroutine cs_fill_phep(n,p)
      implicit none
      include 'hepevt.h'
      integer n,j
      double precision p(0:3,n)
      nhep = n
      do j=1,n
         phep(1,j) = p(1,j)
         phep(2,j) = p(2,j)
         phep(3,j) = p(3,j)
         phep(4,j) = p(0,j)
         phep(5,j) = sqrt(abs(p(0,j)**2-p(1,j)**2-p(2,j)**2
     $        -p(3,j)**2))
         isthep(j) = 1
         if (j.le.2) isthep(j) = -1
         idhep(j) = 0
      enddo
      idhep(3) = 25
      end
